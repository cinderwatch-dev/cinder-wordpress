<?php

namespace Cinderwatch\WordPress\MuPlugin;

/**
 * Writes a must-use plugin that turns on SAVEQUERIES before regular plugins load,
 * so their queries show up in traces. Cinder itself still boots on plugins_loaded.
 */
class MuPluginLoader
{
    private const FILENAME = 'cinder-loader.php';

    public static function install(): bool
    {
        if (! is_dir(WPMU_PLUGIN_DIR) && ! wp_mkdir_p(WPMU_PLUGIN_DIR)) {
            return false;
        }

        $pluginMain = defined('CINDER_PLUGIN_FILE')
            ? (string) constant('CINDER_PLUGIN_FILE')
            : dirname(__DIR__, 2).'/cinder.php';

        $contents = "<?php\n\n"
            ."// Auto-generated by Cinder. Turns on SAVEQUERIES before other plugins load.\n"
            ."if (! defined('SAVEQUERIES')) {\n"
            ."    \$cinderTraceEnabled = ! defined('CINDER_TRACING_ENABLED')\n"
            ."        || filter_var(constant('CINDER_TRACING_ENABLED'), FILTER_VALIDATE_BOOL);\n"
            ."\n"
            ."    if (\$cinderTraceEnabled) {\n"
            ."        define('SAVEQUERIES', true);\n"
            ."    }\n"
            ."}\n"
            ."if (file_exists('".addslashes($pluginMain)."')) {\n"
            ."    require_once '".addslashes($pluginMain)."';\n"
            ."}\n";

        return (bool) file_put_contents(WPMU_PLUGIN_DIR.'/'.self::FILENAME, $contents);
    }

    public static function isInstalled(): bool
    {
        return file_exists(WPMU_PLUGIN_DIR.'/'.self::FILENAME);
    }
}
